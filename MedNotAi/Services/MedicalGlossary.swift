    private static let index: [String: MedicalTerm] = {
        var map: [String: MedicalTerm] = [:]
        for t in terms {
            map[t.term.lowercased()] = t
            for f in t.forms { map[f.lowercased()] = t }
        }
        return map
    }()

    static var categories: [String] {
        Array(Set(terms.map(\.category))).sorted()
    }

    static func term(for word: String) -> MedicalTerm? {
        index[word.lowercased()]
    }

    /// Ищет термин по свободной формулировке: точное совпадение, затем словоформа,
    /// затем упоминание внутри фразы. Нужен ассистенту — пользователь пишет
    /// «что такое ишемию» или «инфаркт миокарда у пожилых», а не словарную статью.
    static func bestMatch(for phrase: String) -> MedicalTerm? {
        let clean = phrase
            .trimmingCharacters(in: CharacterSet.alphanumerics.union(.whitespaces).inverted)
            .trimmingCharacters(in: .whitespaces)
            .lowercased()
        guard !clean.isEmpty else { return nil }

        if let exact = index[clean] { return exact }
        // Термин целиком внутри фразы: самый длинный выигрывает,
        // иначе «инфаркт миокарда» проиграет просто «инфаркту».
        if let contained = index.keys
            .filter({ clean.contains($0) })
            .max(by: { $0.count < $1.count }) {
            return index[contained]
        }
        return matches(in: clean).first?.term ?? search(clean).first
    }

    /// Совпадения в названии термина важнее, чем упоминание внутри определения,
    /// поэтому результаты ранжируются, а не просто сортируются по алфавиту.
    static func search(_ query: String) -> [MedicalTerm] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        guard !q.isEmpty else { return terms.sorted { $0.term < $1.term } }

        func rank(_ term: MedicalTerm) -> Int? {
            let name = term.term.lowercased()
            if name.hasPrefix(q) { return 0 }
            if name.contains(q) { return 1 }
            if term.category.lowercased().contains(q) { return 2 }
            if term.forms.contains(where: { $0.lowercased().hasPrefix(q) }) { return 3 }
            if term.definition.lowercased().contains(q) { return 4 }
            return nil
        }

        var ranked: [(term: MedicalTerm, rank: Int)] = []
        for term in terms {
            if let r = rank(term) {
                ranked.append((term, r))
            }
        }
        ranked.sort { lhs, rhs in
            if lhs.rank != rhs.rank { return lhs.rank < rhs.rank }
            return lhs.term.term < rhs.term.term
        }
        return ranked.map(\.term)
    }

    /// Одно регулярное выражение на все словоформы: длинные варианты идут первыми,
    /// поэтому «инфаркт миокарда» не распадается на «инфаркт» и «миокарда».
    /// Границы слова заданы вручную — `\b` некорректно работает с кириллицей.
    private static let matcher: NSRegularExpression? = {
        let alternatives = index.keys
            .sorted { $0.count > $1.count }
            .map { NSRegularExpression.escapedPattern(for: $0) }
            .joined(separator: "|")
        let pattern = "(?<![\\p{L}\\p{N}])(?:\(alternatives))(?![\\p{L}\\p{N}])"
        return try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive])
    }()

    /// Находит вхождения известных терминов в тексте.
    /// Возвращает диапазоны вместе с термином, отсортированные по позиции.
    static func matches(in text: String) -> [(range: Range<String.Index>, term: MedicalTerm)] {
        guard let matcher, !text.isEmpty else { return [] }
        let full = NSRange(text.startIndex..<text.endIndex, in: text)
        return matcher.matches(in: text, options: [], range: full).compactMap { match in
            guard let range = Range(match.range, in: text),
                  let term = index[text[range].lowercased()] else { return nil }
            return (range, term)
        }
    }
