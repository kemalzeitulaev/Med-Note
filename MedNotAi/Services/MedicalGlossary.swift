struct MedicalTerm: Identifiable, Hashable {
    var id: String { term }
    let term: String
    let category: String
    let definition: String
    /// Дополнительные словоформы для поиска в тексте.
    let forms: [String]

    init(_ term: String, category: String, definition: String, forms: [String] = []) {
        self.term = term
        self.category = category
        self.definition = definition
        self.forms = forms
    }
}

